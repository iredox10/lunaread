static QString escapeCsvField(const QString& field) {
    QString res = field;
    res.replace("\"", "\"\"");
    return QString("\"%1\"").arg(res);
}

QString AnnotationExporter::exportToMarkdown(const QString& bookTitle, const QList<AnnotationRecord>& annotations) {
    QString md = QString("# Annotations for %1\n\n").arg(bookTitle);
    md += QString("*Generated by LunaRead on %1*\n\n---\n\n").arg(QDateTime::currentDateTime().toString(Qt::ISODate));

    for (const auto& a : annotations) {
        if (a.type == "highlight") {
            md += QString("> ==%1==\n").arg(a.selectedText);
            if (!a.note.isEmpty()) {
                md += QString("\n**Note:** %1\n").arg(a.note);
            }
            md += QString("\n*Chapter %1, Page %2*\n\n---\n\n").arg(a.chapterIndex + 1).arg(a.pageIndex + 1);
        } else if (a.type == "note") {
            md += QString("### 📝 Note: Chapter %1, Page %2\n").arg(a.chapterIndex + 1).arg(a.pageIndex + 1);
            if (!a.selectedText.isEmpty()) {
                md += QString("> %1\n\n").arg(a.selectedText);
            }
            md += QString("%1\n\n---\n\n").arg(a.note);
        } else if (a.type == "bookmark") {
            md += QString("### 🔖 Bookmark: %1 (Chapter %2, Page %3)\n\n").arg(a.selectedText).arg(a.chapterIndex + 1).arg(a.pageIndex + 1);
        } else if (a.type == "underline") {
            md += QString("> <u>%1</u>\n\n*Chapter %2, Page %3*\n\n---\n\n").arg(a.selectedText).arg(a.chapterIndex + 1).arg(a.pageIndex + 1);
        } else if (a.type == "strikethrough") {
            md += QString("> ~~%1~~\n\n*Chapter %2, Page %3*\n\n---\n\n").arg(a.selectedText).arg(a.chapterIndex + 1).arg(a.pageIndex + 1);
        }
    }
    return md;
}

